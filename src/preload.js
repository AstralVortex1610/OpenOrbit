const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('orbit', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  testConnection: () => ipcRenderer.invoke('settings:test'),
  listModels: () => ipcRenderer.invoke('settings:models'),
  getThread: () => ipcRenderer.invoke('thread:get'),
  clearThread: () => ipcRenderer.invoke('thread:clear'),
  send: (text, attachments) => ipcRenderer.invoke('chat:send', text, attachments),
  stop: () => ipcRenderer.invoke('chat:stop'),
  stopLane: (id) => ipcRenderer.invoke('lane:stop', id),
  googleConnect: () => ipcRenderer.invoke('google:connect'),
  googleDisconnect: () => ipcRenderer.invoke('google:disconnect'),
  answerApproval: (id, approved) => ipcRenderer.invoke('approval:answer', id, approved),
  answerQuestion: (id, answer) => ipcRenderer.invoke('question:answer', id, answer),
  getTasks: () => ipcRenderer.invoke('tasks:get'),
  toggleTask: (id, enabled) => ipcRenderer.invoke('tasks:toggle', id, enabled),
  deleteTask: (id) => ipcRenderer.invoke('tasks:delete', id),
  runTask: (id) => ipcRenderer.invoke('tasks:runNow', id),
  listMemory: () => ipcRenderer.invoke('memory:list'),
  readMemory: (n) => ipcRenderer.invoke('memory:read', n),
  writeMemory: (n, c) => ipcRenderer.invoke('memory:write', n, c),
  openMemoryFolder: () => ipcRenderer.invoke('memory:openFolder'),
  getUsage: () => ipcRenderer.invoke('usage:get'),
  transcribe: (buf, mime) => ipcRenderer.invoke('voice:transcribe', buf, mime),
  info: () => ipcRenderer.invoke('app:info'),
  phoneTest: () => ipcRenderer.invoke('phone:test'),
  phoneStatus: () => ipcRenderer.invoke('phone:status'),
  phoneNewTopic: () => ipcRenderer.invoke('phone:newTopic'),
  update: { state: () => ipcRenderer.invoke('update:state'), check: () => ipcRenderer.invoke('update:check'), install: () => ipcRenderer.invoke('update:install') },
  phoneUnpairTelegram: () => ipcRenderer.invoke('phone:unpairTelegram'),
  getWakeModel: () => ipcRenderer.invoke('wake:model'),
  wakeHeard: () => ipcRenderer.invoke('wake:heard'),
  live: {
    status: () => ipcRenderer.invoke('live:status'),
    start: () => ipcRenderer.invoke('live:start'),
    stop: () => ipcRenderer.invoke('live:stop'),
    mute: (m) => ipcRenderer.invoke('live:mute', m),
    audio: (buf) => ipcRenderer.send('live:audio', buf),
  },
  voice: {
    base: () => ipcRenderer.invoke('voice:base'),
    cached: () => ipcRenderer.invoke('voice:cached'),
    turn: (t) => ipcRenderer.invoke('voice:turn', t),
    interrupt: (t) => ipcRenderer.invoke('voice:interrupt', t),
    talking: (on) => ipcRenderer.send('voice:talking', on),
    opener: () => ipcRenderer.send('voice:opener'),
    speaking: (on) => ipcRenderer.send('voice:speaking', on),
    log: (line) => ipcRenderer.invoke('voice:log', line),
    brainTest: () => ipcRenderer.invoke('voice:brainTest'),
  },
  ui: { scope: (s) => ipcRenderer.invoke('ui:scope', s) },
  projects: {
    list: () => ipcRenderer.invoke('projects:list'),
    get: (id) => ipcRenderer.invoke('projects:get', id),
    create: (d) => ipcRenderer.invoke('projects:create', d),
    update: (id, p) => ipcRenderer.invoke('projects:update', id, p),
    remove: (id) => ipcRenderer.invoke('projects:delete', id),
    thread: (id) => ipcRenderer.invoke('projects:thread', id),
    clear: (id) => ipcRenderer.invoke('projects:clear', id),
    send: (id, t, a) => ipcRenderer.invoke('projects:send', id, t, a),
    stop: (id) => ipcRenderer.invoke('projects:stop', id),
    openFolder: (id) => ipcRenderer.invoke('projects:openFolder', id),
    openFile: (id, n) => ipcRenderer.invoke('projects:openFile', id, n),
  },
  panels: {
    list: () => ipcRenderer.invoke('panels:list'),
    create: (d) => ipcRenderer.invoke('panels:create', d),
    update: (id, p) => ipcRenderer.invoke('panels:update', id, p),
    move: (id, d) => ipcRenderer.invoke('panels:move', id, d),
    remove: (id) => ipcRenderer.invoke('panels:delete', id),
    refresh: (id) => ipcRenderer.invoke('panels:refresh', id),
  },
  updates: {
    list: () => ipcRenderer.invoke('updates:list'),
    read: (ids) => ipcRenderer.invoke('updates:read', ids),
    clear: () => ipcRenderer.invoke('updates:clear'),
  },
  homeSummary: () => ipcRenderer.invoke('home:summary'),
  win: {
    minimize: () => ipcRenderer.invoke('win:minimize'),
    maximize: () => ipcRenderer.invoke('win:maximize'),
    close: () => ipcRenderer.invoke('win:close'),
  },
  on: (channel, fn) => {
    const ok = ['agent:event', 'tasks:changed', 'ui:focusInput', 'settings:changed', 'live:event', 'voice:progress', 'update:state'];
    if (!ok.includes(channel)) return;
    ipcRenderer.on(channel, (_e, payload) => fn(payload));
  },
});

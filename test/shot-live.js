const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1180, height: 780, show: false, webPreferences: { offscreen: true, preload: path.join(__dirname, 'mock-preload.js'), contextIsolation: true } });
  await win.loadFile(path.join(__dirname, '..', 'renderer', 'index.html'));
  const wait = (ms) => new Promise(r => setTimeout(r, ms));
  await wait(1500);
  await win.webContents.executeJavaScript(`(()=>{const l=document.querySelector('#live');l.classList.add('open');l.dataset.state='speaking';l.style.setProperty('--out','.55');l.style.setProperty('--in','0');
   document.querySelector('#liveEngine').textContent='Gemini Live · Aoede';document.querySelector('#liveStatus').textContent='Orbit is talking. Jump in anytime.';
   document.querySelector('#liveOrbit').textContent="Ha, okay, fair. Your physics test is Friday, so let's do two chapters tonight and keep tomorrow light.";
   document.querySelector('#liveYou').textContent='honestly I do not feel like studying today';})()`);
  await wait(1200);
  fs.writeFileSync(path.join(__dirname, 'shot-live.png'), (await win.webContents.capturePage()).toPNG());
  await win.webContents.executeJavaScript(`(()=>{const l=document.querySelector('#live');l.dataset.state='working';l.style.setProperty('--out','.05');document.querySelector('#liveStatus').textContent='Working: Opening Chrome';document.querySelector('#liveOrbit').textContent='Sure, opening it now.';document.querySelector('#liveYou').textContent='open chrome and search jee main dates';})()`);
  await wait(800);
  fs.writeFileSync(path.join(__dirname, 'shot-live-working.png'), (await win.webContents.capturePage()).toPNG());
  await win.webContents.executeJavaScript(`document.querySelector('#live').classList.remove('open');document.querySelector('[data-view=settings]').click()`);
  await wait(900);
  await win.webContents.executeJavaScript(`document.querySelector('#liveCard').scrollIntoView({block:'start'})`);
  await wait(500);
  fs.writeFileSync(path.join(__dirname, 'shot-live-settings.png'), (await win.webContents.capturePage()).toPNG());
  await win.webContents.executeJavaScript(`document.querySelector('[data-view=chat]').click()`);
  await wait(700);
  fs.writeFileSync(path.join(__dirname, 'shot-live-composer.png'), (await win.webContents.capturePage()).toPNG());
  app.quit();
});
